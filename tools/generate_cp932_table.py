#!/usr/bin/env python3
"""Generate the compact CP932 -> UTF-16 table used by the ARMv5 core.

The generated C++ file is a build artifact, not checked in. CP932 is a single /
double-byte encoding, so a 256-entry single-byte table plus a dense 60x188
lead/trail table covers the complete Windows-31J code page without iconv/ICU
or Symbian locale plug-in dependencies at runtime.
"""

from __future__ import annotations

import argparse
from pathlib import Path

INVALID = 0xFFFF
LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
TRAILS = list(range(0x40, 0x7F)) + list(range(0x80, 0xFD))


def decode_one(raw: bytes) -> int:
    try:
        text = raw.decode("cp932", errors="strict")
    except UnicodeDecodeError:
        return INVALID
    if len(text) != 1:
        return INVALID
    value = ord(text)
    if value > 0xFFFE:
        return INVALID
    return value


def make_tables() -> tuple[list[int], list[int], list[tuple[int, int]]]:
    single = [decode_one(bytes((value,))) for value in range(256)]
    double = [decode_one(bytes((lead, trail))) for lead in LEADS for trail in TRAILS]
    reverse: list[tuple[int, int]] = []
    for codepoint in range(0x10000):
        try:
            raw = chr(codepoint).encode("cp932", errors="strict")
        except UnicodeEncodeError:
            continue
        if len(raw) == 1:
            reverse.append((codepoint, raw[0]))
        elif len(raw) == 2:
            reverse.append((codepoint, (raw[0] << 8) | raw[1]))
    return single, double, reverse


def format_table(name: str, values: list[int], per_line: int = 12) -> str:
    lines = [f"static const unsigned short {name}[{len(values)}] =", "{"]
    for offset in range(0, len(values), per_line):
        chunk = values[offset : offset + per_line]
        encoded = ", ".join(f"0x{value:04x}" for value in chunk)
        suffix = "," if offset + per_line < len(values) else ""
        lines.append(f"    {encoded}{suffix}")
    lines.append("};")
    return "\n".join(lines)


def render(single: list[int], double: list[int], reverse: list[tuple[int, int]]) -> str:
    reverse_codepoints = [item[0] for item in reverse]
    reverse_values = [item[1] for item in reverse]
    return f'''// Generated by tools/generate_cp932_table.py. Do not edit.
#include "easyrpgsymbian/CoreEncoding.h"

namespace
{{
static const unsigned short KInvalid = 0xffffu;
static const unsigned int KTrailsPerLead = {len(TRAILS)}u;

{format_table("KCp932Single", single)}

{format_table("KCp932Double", double)}

{format_table("KUnicodeCodepoints", reverse_codepoints)}

{format_table("KUnicodeCp932", reverse_values)}

int LeadIndex(unsigned int aByte)
{{
    if (aByte >= 0x81u && aByte <= 0x9fu)
        return static_cast<int>(aByte - 0x81u);
    if (aByte >= 0xe0u && aByte <= 0xfcu)
        return static_cast<int>(31u + aByte - 0xe0u);
    return -1;
}}

int TrailIndex(unsigned int aByte)
{{
    if (aByte >= 0x40u && aByte <= 0x7eu)
        return static_cast<int>(aByte - 0x40u);
    if (aByte >= 0x80u && aByte <= 0xfcu)
        return static_cast<int>(63u + aByte - 0x80u);
    return -1;
}}
}}

extern "C" int EasyRpgCoreCp932ToUtf16(const unsigned char* aSource,
                                         unsigned int aSourceLength,
                                         unsigned short* aDestination,
                                         unsigned int aDestinationCapacity,
                                         unsigned int* aDestinationLength)
{{
    if (!aDestinationLength)
        return -1;
    *aDestinationLength = 0;
    if (aSourceLength == 0)
        return 0;
    if (!aSource || !aDestination)
        return -1;

    unsigned int sourcePosition = 0;
    unsigned int destinationPosition = 0;
    while (sourcePosition < aSourceLength)
    {{
        const unsigned int first = aSource[sourcePosition];
        unsigned short value = KCp932Single[first];
        unsigned int consumed = 1;

        if (value == KInvalid)
        {{
            const int leadIndex = LeadIndex(first);
            if (leadIndex < 0 || sourcePosition + 1u >= aSourceLength)
                return -3;

            const unsigned int second = aSource[sourcePosition + 1u];
            const int trailIndex = TrailIndex(second);
            if (trailIndex < 0)
                return -3;

            const unsigned int tableIndex =
                static_cast<unsigned int>(leadIndex) * KTrailsPerLead +
                static_cast<unsigned int>(trailIndex);
            value = KCp932Double[tableIndex];
            if (value == KInvalid)
                return -3;
            consumed = 2;
        }}

        if (destinationPosition >= aDestinationCapacity)
            return -2;
        aDestination[destinationPosition++] = value;
        sourcePosition += consumed;
    }}

    *aDestinationLength = destinationPosition;
    return 0;
}}

extern "C" int EasyRpgCoreUtf16ToCp932(const unsigned short* aSource,
                                         unsigned int aSourceLength,
                                         unsigned char* aDestination,
                                         unsigned int aDestinationCapacity,
                                         unsigned int* aDestinationLength)
{{
    if (!aDestinationLength)
        return -1;
    *aDestinationLength = 0;
    if (aSourceLength == 0)
        return 0;
    if (!aSource || !aDestination)
        return -1;

    unsigned int destinationPosition = 0;
    for (unsigned int sourcePosition = 0; sourcePosition < aSourceLength; ++sourcePosition)
    {{
        const unsigned short codepoint = aSource[sourcePosition];
        unsigned int low = 0;
        unsigned int high = {len(reverse)}u;
        while (low < high)
        {{
            const unsigned int middle = low + (high - low) / 2u;
            if (KUnicodeCodepoints[middle] < codepoint)
                low = middle + 1u;
            else
                high = middle;
        }}
        if (low >= {len(reverse)}u || KUnicodeCodepoints[low] != codepoint)
            return -3;

        const unsigned short encoded = KUnicodeCp932[low];
        const unsigned int bytes = encoded > 0xffu ? 2u : 1u;
        if (destinationPosition + bytes > aDestinationCapacity)
            return -2;
        if (bytes == 2u)
            aDestination[destinationPosition++] = static_cast<unsigned char>(encoded >> 8);
        aDestination[destinationPosition++] = static_cast<unsigned char>(encoded & 0xffu);
    }}

    *aDestinationLength = destinationPosition;
    return 0;
}}
'''


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    single, double, reverse = make_tables()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(single, double, reverse), encoding="utf-8")
    print(
        f"CP932 table: {len(single)} single + {len(double)} double + {len(reverse)} reverse entries -> {args.output}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

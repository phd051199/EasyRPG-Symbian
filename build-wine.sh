#!/usr/bin/env bash
set -Eeuo pipefail

usage() {
    cat <<'EOF'
Usage: bash build-wine.sh [build|debug|clean]

build  GCCE UREL build + unsigned SIS
debug  GCCE UDEB build + unsigned debug SIS
clean  Clean GCCE outputs generated by ABLD

Environment overrides:
  EASYRPG_WINE_PREFIX                Wine prefix (default: ~/.wine-symbian)
  EASYRPG_WINE_BIN                   wine executable
  EASYRPG_SYMBIAN_SDK_ROOT           host SDK path
  EASYRPG_SYMBIAN_SDK_WINDOWS_ROOT   Windows SDK path inside Wine
EOF
}

PROFILE=${1:-build}
case "$PROFILE" in
    build|debug|clean) ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; exit 2 ;;
esac

PROJECT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
BUILD_LOCK="$PROJECT_DIR/build/.build.lock"
mkdir -p "$PROJECT_DIR/build"
if ! mkdir "$BUILD_LOCK" 2>/dev/null; then
    existing_pid=$(cat "$BUILD_LOCK/pid" 2>/dev/null || true)
    if [[ $existing_pid =~ ^[0-9]+$ ]] && kill -0 "$existing_pid" 2>/dev/null; then
        echo "Another EasyRPG build is already running (pid $existing_pid)." >&2
        exit 75
    fi
    rm -rf "$BUILD_LOCK"
    mkdir "$BUILD_LOCK"
fi
printf '%s\n' "$$" > "$BUILD_LOCK/pid"
cleanup_build_lock() {
    rm -rf "$BUILD_LOCK"
}
trap cleanup_build_lock EXIT INT TERM
WINE_PREFIX=${EASYRPG_WINE_PREFIX:-"$HOME/.wine-symbian"}
SDK_HOST_ROOT=${EASYRPG_SYMBIAN_SDK_ROOT:-"$WINE_PREFIX/drive_c/S60/devices/S60_3rd_FP2_SDK_v1.1"}
SDK_WINDOWS_ROOT=${EASYRPG_SYMBIAN_SDK_WINDOWS_ROOT:-'C:\S60\devices\S60_3rd_FP2_SDK_v1.1'}
PROJECT_LINK="$WINE_PREFIX/drive_c/work/EasyRPG"
PROJECT_WINDOWS_ROOT='C:\work\EasyRPG'

find_wine() {
    if [[ -n ${EASYRPG_WINE_BIN:-} ]]; then
        printf '%s\n' "$EASYRPG_WINE_BIN"
        return
    fi

    local candidate
    for candidate in \
        "$HOME/Applications/Wine Stable.app/Contents/Resources/wine/bin/wine" \
        "/Applications/Wine Stable.app/Contents/Resources/wine/bin/wine"; do
        if [[ -x $candidate ]]; then
            printf '%s\n' "$candidate"
            return
        fi
    done

    command -v wine 2>/dev/null || true
}

WINE_BIN=$(find_wine)
if [[ -z $WINE_BIN || ! -x $WINE_BIN ]]; then
    echo 'Wine executable not found. Set EASYRPG_WINE_BIN.' >&2
    exit 1
fi

for required in \
    "$SDK_HOST_ROOT/epoc32/tools/bldmake.bat" \
    "$SDK_HOST_ROOT/epoc32/tools/makesis.exe" \
    "$WINE_PREFIX/drive_c/Perl/bin/perl.exe" \
    "$WINE_PREFIX/drive_c/Program Files/CSL Arm Toolchain/bin/arm-none-symbianelf-g++.exe"; do
    if [[ ! -e $required ]]; then
        printf 'Missing Symbian build dependency: %s\n' "$required" >&2
        exit 1
    fi
done

mkdir -p "$(dirname -- "$PROJECT_LINK")"
if [[ -L $PROJECT_LINK ]]; then
    current=$(cd -- "$(dirname -- "$PROJECT_LINK")" && cd -- "$(readlink "$PROJECT_LINK")" && pwd)
    if [[ $current != "$PROJECT_DIR" ]]; then
        rm "$PROJECT_LINK"
        ln -s "$PROJECT_DIR" "$PROJECT_LINK"
    fi
elif [[ -e $PROJECT_LINK ]]; then
    printf 'Wine project path exists and is not a symlink: %s\n' "$PROJECT_LINK" >&2
    exit 1
else
    ln -s "$PROJECT_DIR" "$PROJECT_LINK"
fi

export WINEPREFIX="$WINE_PREFIX"
export WINEDEBUG=-all
export MVK_CONFIG_LOG_LEVEL=0
export DXVK_LOG_LEVEL=none

printf 'EasyRPG: %s\n' "$PROJECT_DIR"
printf 'S60 SDK: %s\n' "$SDK_HOST_ROOT"
printf 'Profile: %s\n' "$PROFILE"

if [[ $PROFILE != clean ]]; then
    bash "$PROJECT_DIR/tools/prepare_third_party.sh"
    EASYRPG_SYMBIAN_SDK_ROOT="$SDK_HOST_ROOT" \
    EASYRPG_WINE_BIN="$WINE_BIN" \
        bash "$PROJECT_DIR/tools/build_player.sh" "$PROFILE"
fi

WINDOWS_BUILD_COMMAND="set EASYRPG_SYMBIAN_SDK_ROOT=${SDK_WINDOWS_ROOT}&& ${PROJECT_WINDOWS_ROOT}\\tools\\build.cmd ${PROFILE}"
if [[ $PROFILE == clean ]]; then
    "$WINE_BIN" cmd.exe /d /s /c "$WINDOWS_BUILD_COMMAND"
    rm -rf "$PROJECT_DIR/build"
    exit 0
fi

"$WINE_BIN" cmd.exe /d /s /c "$WINDOWS_BUILD_COMMAND"
